"""Build local, readable AureaSim projects from private evaluation inputs.

The process-mining repository is intentionally not published.  This helper is
therefore for a local development workspace only: it copies one frozen semantic
baseline per evaluated process and attaches only the aggregate chronological
hold-out references needed by the web interface.
"""

from __future__ import annotations

import csv
import json
import shutil
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class EvaluationProject:
    alias: str
    research_id: str
    directory_name: str
    display_name: str
    icon: str
    color: str


PROJECTS = (
    EvaluationProject("P01", "bm__OBIEG_FAKTURY_KOSZTOWEJ__v2.4.2.2", "evaluation_cost_invoice_workflow", "Cost Invoice Workflow", "mdi-file-document-check-outline", "indigo"),
    EvaluationProject("P02", "kw_mty__DOW3__v1.13", "evaluation_embargo_iv", "Embargo IV", "mdi-shield-lock-outline", "deep-purple"),
    EvaluationProject("P03", "kw_mty__TNP_P1__v1.27", "evaluation_milk_support_application", "Milk Support Application", "mdi-cow", "teal"),
    EvaluationProject("P04", "kw_pds__PDS_WNI_POMOC__v2.1.40", "evaluation_aid_application_settlement", "Aid Application Settlement", "mdi-cash-check", "blue"),
    EvaluationProject("P05", "kw_ppw__MKW_WPIS__v1.1992", "evaluation_registry_entry_application", "Registry Entry Application", "mdi-notebook-edit-outline", "green"),
    EvaluationProject("P06", "nm__NMM_OBIFAK__v5.60", "evaluation_cost_document_workflow", "Cost Document Workflow", "mdi-file-table-outline", "orange"),
    EvaluationProject("P07", "pk__PKP_DEL__v5.10", "evaluation_business_travel_request", "Business Travel Delegation Request", "mdi-briefcase-outline", "cyan"),
)


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def build(base_dir: Path) -> list[Path]:
    """Create or refresh the seven ignored local evaluation projects."""
    source_root = base_dir.parent / "research" / "process_mining" / "data"
    baselines_root = source_root / "research_baselines"
    evaluation_root = source_root / "research_operational_evaluation"
    projects_root = base_dir / "projects"
    references = _read_csv(evaluation_root / "operational_references.csv")
    comparisons = _read_csv(evaluation_root / "generated_parameter_comparisons.csv")
    created: list[Path] = []

    for spec in PROJECTS:
        source_run = baselines_root / spec.research_id / "semantic_label_heuristic" / "run_001"
        if not source_run.exists():
            raise FileNotFoundError(f"Missing frozen run: {source_run}")
        target = projects_root / spec.directory_name
        target.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source_run / "input.bpmn", target / f"{spec.directory_name}.bpmn")
        shutil.copy2(source_run / "AutoGenerated_Base_params.json", target / "AutoGenerated_Base_params.json")

        eligible_ids = {
            row["entity_id"]
            for row in comparisons
            if row["process_alias"] == spec.alias
            and row["condition"] == "semantic_label_heuristic"
            and row["repetition"] == "1"
            and row["parameter_family"] == "execution_duration_seconds"
            and row["primary_score_eligible"] == "1"
        }
        matched = [
            row for row in references
            if row["process_alias"] == spec.alias
            and row["split"] == "holdout"
            and row["metric"] == "execution_duration_seconds"
            and row["entity_id"] in eligible_ids
        ]
        payload = {
            "format_version": 1,
            "reference_type": "chronological_operational_holdout",
            "process_alias": spec.alias,
            "description": "Independent aggregate process-mining reference for eligible human-task execution durations.",
            "references": matched,
        }
        (target / "operational_references.json").write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        (target / "project_config.json").write_text(
            json.dumps({"display_name": spec.display_name, "icon": spec.icon, "color": spec.color}, indent=2) + "\n",
            encoding="utf-8",
        )
        created.append(target)
    return created


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    for project in build(root):
        print(project)
