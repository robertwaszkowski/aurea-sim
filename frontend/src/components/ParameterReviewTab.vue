async function submitReview() {
  dialogError.value = ''
  if (!reviewerId.value.trim() || justification.value.trim().length < 8) {
    dialogError.value = 'Reviewer identifier and a justification of at least eight characters are required.'
    return
  }
  const body: Record<string, any> = {
    action: selectedAction.value,
    reviewer_id: reviewerId.value.trim(),
    justification: justification.value.trim(),
  }
  if (selectedAction.value === 'edit') {
    try {
      const parsed = JSON.parse(replacementValue.value)
      if (typeof parsed === 'number') body.scalar_value = parsed
      else if (parsed && typeof parsed === 'object') body.distribution = parsed
      else throw new Error('Replacement must be a number or distribution object.')
    } catch (reason) {
      dialogError.value = reason instanceof Error ? reason.message : 'Replacement value is not valid JSON.'
      return
    }
  }
  submitting.value = true
  try {
    const identifier = encodeURIComponent(selectedCandidate.value.candidate_id)
    const response = await fetch(
      `/api/projects/${encodeURIComponent(props.projectName)}/parameter-candidates/${identifier}/review`,
      { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) },
    )
    if (!response.ok) {
      const data = await response.json().catch(() => ({}))
      throw new Error(data.detail || `HTTP ${response.status}`)
    }
    reviewDialog.value = false
    await fetchCandidates()
  } catch (reason) {
    dialogError.value = reason instanceof Error ? reason.message : 'Could not record the review decision.'
  } finally {
    submitting.value = false
  }
}

