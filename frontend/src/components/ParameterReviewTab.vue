const candidateGroups = computed(() => {
  const groups = new Map<string, any>()
  for (const candidate of candidates.value) {
    const key = `${candidate.parameter_family}::${candidate.entity_id}`
    if (!groups.has(key)) {
      groups.set(key, {
        key,
        parameterFamily: candidate.parameter_family,
        entityId: candidate.entity_id,
        entityName: candidate.entity_name || candidate.entity_id,
        candidates: [],
      })
    }
    groups.get(key).candidates.push(candidate)
  }
  return Array.from(groups.values()).sort((left, right) =>
    `${left.parameterFamily}:${left.entityName}`.localeCompare(`${right.parameterFamily}:${right.entityName}`),
  )
})

const validationAlertType = computed<'success' | 'error' | 'warning' | 'info'>(() => ({
  valid: 'success', invalid: 'error', stale: 'warning', not_validated: 'info', unreadable: 'error',
} as Record<string, 'success' | 'error' | 'warning' | 'info'>)[validationState.value?.status] ?? 'info')

const validationLabel = computed(() => ({
  valid: 'The current executable baseline is valid.',
  invalid: 'The baseline is invalid and cannot be frozen.',
  stale: 'The baseline changed after its last validation.',
  not_validated: 'The baseline has not yet been validated.',
  unreadable: 'The saved validation report is unreadable.',
} as Record<string, string>)[validationState.value?.status] ?? 'Validation state is unknown.')

function humanize(value: string | undefined): string {
  if (!value) return ''
  return value.replace(/_/g, ' ').replace(/\b\w/g, letter => letter.toUpperCase())
}

function confidenceColor(value: string): string {
  return ({ high: 'success', medium: 'warning', low: 'error', unknown: 'grey' } as Record<string, string>)[value] ?? 'grey'
}

function statusColor(value: string): string {
  return ({ accepted: 'success', edited: 'info', rejected: 'error', locked: 'primary', pending: 'warning' } as Record<string, string>)[value] ?? 'grey'
}

function statusCount(status: string): number {
  return candidates.value.filter(candidate => candidate.review_status === status).length
}

function formatCandidateValue(candidate: any): string {
  if (candidate.scalar_value !== null && candidate.scalar_value !== undefined) {
    return `${Number(candidate.scalar_value).toLocaleString()} ${candidate.unit}`
  }
  const distribution = candidate.distribution
  if (!distribution) return 'No value'
  const quantiles = distribution.empirical_quantiles ?? {}
  if (quantiles.p50 !== undefined) return `${humanize(distribution.distribution_name)} · p50 ${Number(quantiles.p50).toLocaleString()} ${candidate.unit}`
  return `${humanize(distribution.distribution_name)} · ${distribution.distribution_params?.join(', ') ?? ''}`
}

function formatErrorPercent(value: unknown): string {
  const percent = Number(value) * 100
  if (!Number.isFinite(percent)) return 'unknown'
  if (percent >= 10000) return `${Math.round(percent).toLocaleString()}%`
  if (percent >= 100) return `${percent.toFixed(0)}%`
  return `${percent.toFixed(1)}%`
}

function expectedErrorRange(candidate: any): string {
  const profile = candidate.reliability_profile
  const expected = candidate.expected_error
  const p10 = profile?.expected_error_p10 ?? expected?.p10
  const median = profile?.expected_error_median ?? expected?.median
  const p90 = profile?.expected_error_p90 ?? expected?.p90
  if ([p10, median, p90].some(value => value === undefined || value === null)) {
    return median === undefined || median === null
      ? 'No empirical error range'
      : `Median ${formatErrorPercent(median)}`
  }
  return `p10 ${formatErrorPercent(p10)} · median ${formatErrorPercent(median)} · p90 ${formatErrorPercent(p90)}`
}

function reliabilityContext(candidate: any): string {
  const profile = candidate.reliability_profile
  if (!profile) return 'No matching research profile'
  return `${humanize(profile.reference_context)} · n=${profile.independent_units}`
}

function evidenceSource(candidate: any): string {
  const source = candidate.evidence?.[0]?.source
  if (!source) return 'Source unavailable'
  return source.replace('AutoGenerated_Base_params.json#', 'Generated baseline · ')
}

function evidenceSummary(candidate: any): string {
  const evidence = candidate.evidence ?? []
  const notes = evidence[0]?.notes || candidate.confidence_basis || ''
  const suffix = evidence.length > 1 ? ` · +${evidence.length - 1} source${evidence.length === 2 ? '' : 's'}` : ''
  const summary = `${notes}${suffix}`
  return summary.length > 180 ? `${summary.slice(0, 177)}…` : summary
}

function measuredFidelity(candidate: any): string {
  if (!candidate.measured_fidelity) return 'Not measured'
  const value = candidate.measured_fidelity.relative_error ?? candidate.measured_fidelity.median
  return value === undefined ? 'Measured reference available' : `${(Number(value) * 100).toFixed(1)}% error`
}

function fidelityReference(candidate: any): string {
  const fidelity = candidate.measured_fidelity
  if (!fidelity) return ''
  const type = fidelity.reference_type === 'expert_survey_reference'
    ? 'Expert-survey reference'
    : fidelity.reference_type === 'operational_reference'
      ? 'Operational reference'
      : 'Independent reference'
  return fidelity.source ? `${type} · ${fidelity.source}` : type
}

