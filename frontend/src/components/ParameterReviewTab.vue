async function fetchCandidates() {
  loading.value = true
  error.value = ''
  try {
    const response = await fetch(`/api/projects/${encodeURIComponent(props.projectName)}/parameter-candidates`)
    if (!response.ok) {
      const body = await response.json().catch(() => ({}))
      throw new Error(body.detail || `HTTP ${response.status}`)
    }
    let data = await response.json()
    if (!data.available) {
      const initialized = await fetch(
        `/api/projects/${encodeURIComponent(props.projectName)}/parameter-candidates/initialize`,
        { method: 'POST' },
      )
      const initializedBody = await initialized.json().catch(() => ({}))
      if (!initialized.ok) throw new Error(initializedBody.detail || `HTTP ${initialized.status}`)
      const refreshed = await fetch(`/api/projects/${encodeURIComponent(props.projectName)}/parameter-candidates`)
      if (!refreshed.ok) {
        const body = await refreshed.json().catch(() => ({}))
        throw new Error(body.detail || `HTTP ${refreshed.status}`)
      }
      data = await refreshed.json()
    }
    available.value = data.available
    candidates.value = data.candidate_set?.candidates ?? []
    reviewQueue.value = data.review_queue ?? []
    auditEventCount.value = data.audit_event_count ?? 0
    auditChainValid.value = data.audit_chain_valid !== false
    activeCandidateIds.value = data.active_candidate_ids ?? []
    emit('candidateAvailability', candidates.value.map(candidateKey))
  } catch (reason) {
    error.value = reason instanceof Error ? reason.message : 'Could not load parameter candidates.'
  } finally {
    loading.value = false
  }
}

